import { expect, test } from "bun:test";
import { readdirSync, readFileSync } from "node:fs";
import * as path from "node:path";
import { YAML } from "bun";
import {
	ATLAS_AGENT_NAMES,
	ATLAS_DEFAULT_FALLBACK_ROLE,
	ATLAS_THINKING_LEVELS,
	modelPatternsFor,
	roleFor,
	SMOL_FALLBACK_ROLE,
} from "./atlas-agents";
import { generateAgents, renderGeneratedAgent } from "./gen-agents";

const agentsDir = path.resolve(import.meta.dir, "..", "agents");
const outDir = path.resolve(import.meta.dir, "agents");

function claudeAgentSources(): Record<string, string> {
	const sources: Record<string, string> = {};
	for (const file of readdirSync(agentsDir).filter(file => file.endsWith(".md"))) {
		const content = readFileSync(path.join(agentsDir, file), "utf8");
		const name = YAML.parse(content.slice(content.indexOf("---") + 3, content.indexOf("\n---", 4))).name;
		sources[name] = content;
	}
	return sources;
}

function generatedAgents(): Record<string, string> {
	const files: Record<string, string> = {};
	for (const file of readdirSync(outDir).filter(file => file.endsWith(".md"))) {
		files[file.replace(/\.md$/, "")] = readFileSync(path.join(outDir, file), "utf8");
	}
	return files;
}

function frontmatterOf(content: string): Record<string, unknown> {
	return YAML.parse(content.slice(content.indexOf("---") + 3, content.indexOf("\n---", 4))) as Record<string, unknown>;
}

test("every Claude agent has an omp counterpart with the mapped thinkingLevel, role, and body", () => {
	const sources = claudeAgentSources();
	expect(Object.keys(sources).sort()).toEqual([...ATLAS_AGENT_NAMES].sort());
	const generated = generatedAgents();
	expect(Object.keys(generated).sort()).toEqual([...ATLAS_AGENT_NAMES].sort());
	for (const [name, source] of Object.entries(sources)) {
		const { frontmatter, body } = { ...parseSource(source) };
		const fm = frontmatterOf(generated[name]);
		expect(fm.name).toBe(name);
		expect(fm.description).toBe(frontmatter.description);
		expect(fm.thinkingLevel).toBe(ATLAS_THINKING_LEVELS[name]);
		const model = fm.model as string[];
		expect(model[0]).toBe(roleFor(name));
		expect(model[1]).toBe(ATLAS_THINKING_LEVELS[name] === "medium" ? ATLAS_DEFAULT_FALLBACK_ROLE : SMOL_FALLBACK_ROLE);
		expect(fm.spawns).toBe("none");
		expect(generated[name].endsWith(body) || generated[name].endsWith(body + "\n")).toBe(true);
	}
});

function parseSource(source: string): { frontmatter: Record<string, unknown>; body: string } {
	const closeIndex = source.indexOf("\n---", 4);
	return {
		frontmatter: YAML.parse(source.slice(3, closeIndex)) as Record<string, unknown>,
		body: source.slice(closeIndex + 4).replace(/^\n/, ""),
	};
}

test("generated files carry the GENERATED header", () => {
	for (const content of Object.values(generatedAgents())) {
		expect(content).toContain("# GENERATED by omp/gen-agents.ts");
		expect(content).toContain("do not edit by hand");
	}
});

test("re-running the generator produces no diff against the committed output", () => {
	const before: Record<string, string> = generatedAgents();
	const { written } = generateAgents({ agentsDir, outDir });
	expect(written).toEqual([]);
	expect(generatedAgents()).toEqual(before);
});

test("renderGeneratedAgent YAML-safes descriptions and keeps the body verbatim", () => {
	const source = [
		"---",
		'name: "db-prober"',
		"description: \"Handles: colons, \\\"quotes\\\", and [brackets] fine.\"",
		"model: sonnet",
		"effort: low",
		"color: yellow",
		"---",
		"",
		"Body line one.",
		"Body line two with `code`.",
		"",
	].join("\n");
	const rendered = renderGeneratedAgent("db-prober.md", source);
	expect(rendered).not.toBeNull();
	const fm = frontmatterOf(rendered as string);
	expect(fm.name).toBe("db-prober");
	expect(fm.description).toBe("Handles: colons, \"quotes\", and [brackets] fine.");
	expect(fm.thinkingLevel).toBe(ATLAS_THINKING_LEVELS["db-prober"]);
	expect(fm.model).toEqual(modelPatternsFor("db-prober"));
	expect(rendered).toContain("Body line one.\nBody line two with `code`.");
});

test("unknown agent names are rejected instead of guessed", () => {
	const source = "---\nname: mystery-agent\ndescription: Not in the colony map.\n---\n\nBody.\n";
	expect(() => renderGeneratedAgent("mystery-agent.md", source)).toThrow("mystery-agent");
});