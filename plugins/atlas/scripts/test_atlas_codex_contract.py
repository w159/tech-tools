class MainCli(unittest.TestCase):
    def setUp(self):
        self._t = tempfile.TemporaryDirectory()
        self.addCleanup(self._t.cleanup)
        self.target = Path(self._t.name) / "AGENTS.md"
        p = mock.patch.object(g, "TARGET", self.target)
        p.start()
        self.addCleanup(p.stop)

    def call(self, argv):
        out = io.StringIO()
        with contextlib.redirect_stdout(out):
            rc = g.main(argv)
        return rc, out.getvalue()

    def test_no_flag_prints_block_and_leaves_file_alone(self):
        self.target.write_text("untouched")
        rc, out = self.call([])
        self.assertEqual(rc, 0)
        self.assertEqual(out, g.render() + "\n")
        self.assertEqual(self.target.read_text(), "untouched")

    def test_check_reports_ok_with_exit_zero(self):
        self.target.write_text(g.write("# T\n", g.render()))
        rc, out = self.call(["--check"])
        self.assertEqual((rc, out), (0, "ok\n"))

    def test_check_reports_stale_with_exit_one_and_hint(self):
        self.target.write_text("# T\n")
        with mock.patch.object(sys, "argv", ["acc.py"]):
            rc, out = self.call(["--check"])
        self.assertEqual(rc, 1)
        self.assertEqual(out, "stale: run acc.py --write\n")

    def test_check_does_not_modify_the_file(self):
        self.target.write_text("# T\n")
        self.call(["--check"])
        self.assertEqual(self.target.read_text(), "# T\n")

    def test_write_flag_writes_and_prints_nothing(self):
        self.target.write_text("# T\n")
        rc, out = self.call(["--write"])
        self.assertEqual((rc, out), (0, ""))
        self.assertEqual(self.target.read_text(), "# T\n\n" + g.render() + "\n")

    def test_check_wins_over_write_when_both_given(self):
        self.target.write_text("# T\n")
        self.call(["--check", "--write"])
        self.assertEqual(self.target.read_text(), "# T\n")

    def test_help_prints_usage_without_reading_target(self):
        for flag in ("-h", "--help"):
            rc, out = self.call(["--check", flag])
            self.assertEqual(rc, 0)
            self.assertIn("usage: atlas_codex_contract.py", out)
            self.assertIn("--write", out)
        self.assertFalse(self.target.exists())  # --help never touched/created it

    def test_real_agents_md_block_is_current(self):
        # the repo's own AGENTS.md carries the generated fence in sync with the sources
        real = g.ROOT.parents[1] / "AGENTS.md"
        if not real.exists():
            self.skipTest("no repo AGENTS.md")
        text = real.read_text()
        if g.current(text) is None:
            self.skipTest("AGENTS.md has no atlas:contract fence")
        self.assertEqual(g.current(text), g.render())


