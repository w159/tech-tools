class FakeRoot(unittest.TestCase):
    """render() against a hand-built plugin root so every output byte is predictable."""

    CONTRACT = {
        "headerTemplate": "HDR | <g> <p> | <s>",
        "phases": [{"glyph": "G1", "id": "alpha"}, {"glyph": "G2", "id": "beta"}],
    }

    def setUp(self):
        self._t = tempfile.TemporaryDirectory()
        self.addCleanup(self._t.cleanup)
        self.root = Path(self._t.name)
        (self.root / "contracts").mkdir()
        (self.root / "agents").mkdir()
        (self.root / "contracts" / "operating-contract.json").write_text(
            json.dumps(self.CONTRACT)
        )
        (self.root / "agents" / "zeta.md").write_text(
            "---\nname: zeta\nmodel: opus\neffort: high\ntier_allow: [opus]\n---\nbody model: no\n"
        )
        (self.root / "agents" / "alpha.md").write_text(
            "---\nname: alpha\nmodel: sonnet\n---\n# alpha\neffort: leaked\n"
        )
        (self.root / "agents" / "notes.txt").write_text("not an agent")
        p = mock.patch.object(g, "ROOT", self.root)
        p.start()
        self.addCleanup(p.stop)

    def test_render_exact_block(self):
        blocks = ", ".join(b[0] for b in g.REQUIRED_SPEC_BLOCKS)
        want = "\n".join(
            [
                g.BEGIN,
                "<!-- Generated by plugins/atlas/scripts/atlas_codex_contract.py --write. Do not edit by hand. -->",
                "### Atlas operating contract (generated)",
                "",
                "Nothing enforces this under Codex (no hooks, no dispatch gate); follow it by hand.",
                "",
                "- Open every reply with `HDR | <g> <p> | <s>`. Phases: G1 alpha G2 beta.",
                "- Evidence before done: do not say fixed, done, or working without running the verifying command and showing its output in the same message.",
                f"- Every subagent dispatch prompt carries: {blocks}.",
                "- Tiers (agents/*.md frontmatter):",
                "",
                "| role | model | effort | tier_allow |",
                "|---|---|---|---|",
                "| alpha | sonnet | ? | ? |",
                "| zeta | opus | high | [opus] |",
                g.END,
            ]
        )
        self.assertEqual(g.render(), want)

    def test_rows_sorted_by_filename_and_only_md_files(self):
        out = g.render()
        self.assertLess(out.index("| alpha |"), out.index("| zeta |"))
        self.assertNotIn("notes", out)

    def test_missing_frontmatter_keys_render_as_question_mark(self):
        self.assertIn("| alpha | sonnet | ? | ? |", g.render())

    def test_frontmatter_body_text_is_not_read(self):
        # "effort: leaked" sits after the closing fence of alpha.md
        self.assertNotIn("leaked", g.render())
        self.assertNotIn("model: no", g.render())

    def test_fm_parses_key_values_only_before_fence(self):
        p = self.root / "agents" / "zeta.md"
        self.assertEqual(
            g._fm(p),
            {"name": "zeta", "model": "opus", "effort": "high", "tier_allow": "[opus]"},
        )

    def test_fm_ignores_indented_and_hyphenated_keys(self):
        p = self.root / "x.md"
        p.write_text(
            "---\nname: x\n  nested: no\nbad-key: no\nok_key:   spaced  \n---\n"
        )
        self.assertEqual(g._fm(p), {"name": "x", "ok_key": "spaced  "})


class CurrentAndWrite(unittest.TestCase):
    def test_current_returns_fenced_span_inclusive(self):
        text = "pre\n" + g.BEGIN + "\nmid\n" + g.END + "\npost"
        self.assertEqual(g.current(text), g.BEGIN + "\nmid\n" + g.END)

    def test_current_none_when_either_marker_missing(self):
        self.assertIsNone(g.current("no markers"))
        self.assertIsNone(g.current(g.BEGIN + " only"))
        self.assertIsNone(g.current(g.END + " only"))

    def test_current_none_when_end_precedes_begin(self):
        self.assertIsNone(g.current(g.END + "\n" + g.BEGIN))

    def test_current_begin_at_offset_zero_is_found(self):
        self.assertEqual(g.current(g.BEGIN + g.END), g.BEGIN + g.END)

    def test_write_replaces_only_the_first_fence(self):
        fence = g.BEGIN + "\nold\n" + g.END
        out = g.write("a\n" + fence + "\nb\n" + fence + "\nc", "NEW")
        self.assertEqual(out, "a\nNEW\nb\n" + fence + "\nc")

    def test_write_appends_with_blank_line_and_single_trailing_newline(self):
        self.assertEqual(g.write("# T\n\n\n", "BLK"), "# T\n\nBLK\n")

    def test_write_into_empty_text(self):
        self.assertEqual(g.write("", "BLK"), "\n\nBLK\n")

    def test_write_is_idempotent(self):
        blk = g.BEGIN + "\nBLK\n" + g.END
        once = g.write("# T\n", blk)
        self.assertEqual(g.write(once, blk), once)


