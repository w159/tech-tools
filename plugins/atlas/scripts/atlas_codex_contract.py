#!/usr/bin/env python3
"""Render the atlas operating contract into a fenced block of the repo AGENTS.md.

Codex reads AGENTS.md (project root down to cwd) and runs no atlas hooks, so this
block is the only part of the contract it sees. Sources: contracts/operating-contract.json,
agents/*.md frontmatter, hooks/dispatch_tripwire_core.REQUIRED_SPEC_BLOCKS.
CLI: atlas_codex_contract.py --check | --write | (no flag: print block)
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "hooks"))
from dispatch_tripwire_core import REQUIRED_SPEC_BLOCKS  # noqa: E402

BEGIN = "<!-- atlas:contract:begin -->"
END = "<!-- atlas:contract:end -->"
TARGET = ROOT.parents[1] / "AGENTS.md"


def _fm(path):
    head = path.read_text().split("\n---", 1)[0]
    return dict(re.findall(r"^(\w+):\s*(.+)$", head, re.M))


def render():
    c = json.loads((ROOT / "contracts" / "operating-contract.json").read_text())
    phases = " ".join(f"{p['glyph']} {p['id']}" for p in c["phases"])
    blocks = ", ".join(b[0] for b in REQUIRED_SPEC_BLOCKS)
    rows = []
    for f in sorted((ROOT / "agents").glob("*.md")):
        m = _fm(f)
        rows.append(f"| {f.stem} | {m.get('model', '?')} | {m.get('effort', '?')} | {m.get('tier_allow', '?')} |")
    return "\n".join([
        BEGIN,
        "<!-- Generated by plugins/atlas/scripts/atlas_codex_contract.py --write. Do not edit by hand. -->",
        "### Atlas operating contract (generated)",
        "",
        "Nothing enforces this under Codex (no hooks, no dispatch gate); follow it by hand.",
        "",
        f"- Open every reply with `{c['headerTemplate']}`. Phases: {phases}.",
        "- Evidence before done: do not say fixed, done, or working without running the verifying command and showing its output in the same message.",
        f"- Every subagent dispatch prompt carries: {blocks}.",
        "- Tiers (agents/*.md frontmatter):",
        "",
        "| role | model | effort | tier_allow |",
        "|---|---|---|---|",
        *rows,
        END,
    ])


def current(text):
    i, j = text.find(BEGIN), text.find(END)
    return None if i < 0 or j < i else text[i : j + len(END)]


def write(text, block):
    old = current(text)
    if old is not None:
        return text.replace(old, block, 1)
    return text.rstrip("\n") + "\n\n" + block + "\n"


def main(argv):
    block = render()
    text = TARGET.read_text()
    if "--check" in argv:
        ok = current(text) == block
        print("ok" if ok else f"stale: run {sys.argv[0]} --write")
        return 0 if ok else 1
    if "--write" in argv:
        TARGET.write_text(write(text, block))
        return 0
    print(block)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
