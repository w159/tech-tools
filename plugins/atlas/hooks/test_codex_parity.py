class CodexAgents(unittest.TestCase):
    """Role files in the format codex-rs agent-roles parses (parse_agent_role_file_contents):
    name, description, developer_instructions required; unknown top-level keys rejected."""

    ALLOWED = {"name", "description", "developer_instructions", "model_reasoning_effort", "nickname_candidates"}

    def test_every_agent_converts_to_a_valid_role_file(self):
        import tomllib

        files = atlas_codex_agents.convert()
        self.assertEqual(len(files), len(list((PLUGIN / "agents").glob("*.md"))))
        for fname, text in files.items():
            doc = tomllib.loads(text)
            self.assertLessEqual(set(doc), self.ALLOWED, fname)
            self.assertEqual(doc["name"], fname[:-5])
            self.assertTrue(doc["name"].startswith("atlas-"))
            self.assertTrue(doc["description"].strip() and doc["developer_instructions"].strip())
            self.assertIn(doc.get("model_reasoning_effort", "low"), ("low", "medium", "high"))

    def test_read_only_agents_are_told_not_to_edit(self):
        import tomllib

        verifier = tomllib.loads(atlas_codex_agents.convert()["atlas-verifier.toml"])
        implementer = tomllib.loads(atlas_codex_agents.convert()["atlas-implementer.toml"])
        self.assertIn("read-only agent", verifier["developer_instructions"])
        self.assertNotIn("read-only agent", implementer["developer_instructions"])

    def test_cli_writes_to_the_target_only_and_refuses_the_plugin(self):
        out = Path(tempfile.mkdtemp()) / "agents"
        (out.parent / "keep.toml").write_text("x = 1\n")
        r = subprocess.run([sys.executable, str(PLUGIN / "scripts" / "atlas_codex_agents.py"), str(out), "--plugin-root", "/abs/plugin"],
                           capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual(len(list(out.glob("atlas-*.toml"))), len(list((PLUGIN / "agents").glob("*.md"))))
        self.assertNotIn("${CLAUDE_PLUGIN_ROOT}", "".join(p.read_text("utf-8") for p in out.glob("*.toml")))
        chk = subprocess.run([sys.executable, str(PLUGIN / "scripts" / "atlas_codex_agents.py"), str(out), "--plugin-root", "/abs/plugin", "--check"],
                             capture_output=True, text=True)
        self.assertEqual(chk.returncode, 0, chk.stdout)
        bad = subprocess.run([sys.executable, str(PLUGIN / "scripts" / "atlas_codex_agents.py"), str(PLUGIN / "agents" / "x")], capture_output=True, text=True)
        self.assertEqual(bad.returncode, 2)
        self.assertFalse((PLUGIN / "agents" / "x").exists())

    def test_default_target_is_the_project_codex_dir(self):
        d = tempfile.mkdtemp()
        r = subprocess.run([sys.executable, str(PLUGIN / "scripts" / "atlas_codex_agents.py")], cwd=d, capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertTrue((Path(d) / ".codex" / "agents" / "atlas-implementer.toml").is_file())


