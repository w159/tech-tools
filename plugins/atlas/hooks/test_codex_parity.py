class HookCommandsResolve(unittest.TestCase):
    def _argv(self, command, env):
        """The argv the shell builds for `command`: python3 is shadowed by a function that prints."""
        shim = 'python3() { printf "%s\\n" "$@"; }; ' + command
        r = subprocess.run(["bash", "-c", shim], env=env, capture_output=True, text=True)
        return r.stdout.splitlines()

    def _check_env(self, env):
        for command in _commands():
            self.assertRegex(command, r"\$\{CLAUDE_PLUGIN_ROOT\}/", command)
            argv = self._argv(command, env)
            script = next(a for a in argv if a.endswith(".py"))
            self.assertTrue(Path(script).is_file(), (command, argv))

    def test_claude_env(self):
        self._check_env(_env(CLAUDE_PLUGIN_ROOT=str(PLUGIN)))

    def test_codex_env_sets_both_variables(self):
        """Codex injects PLUGIN_ROOT and CLAUDE_PLUGIN_ROOT (codex-rs/hooks discovery.rs)."""
        self._check_env(_env(PLUGIN_ROOT=str(PLUGIN), CLAUDE_PLUGIN_ROOT=str(PLUGIN)))

    def test_event_dispatch_command_runs_in_both_envs(self):
        cmd = next(c for c in _commands() if "event_dispatch.py" in c)
        payload = json.dumps({"hook_event_name": "PreToolUse", "tool_name": "Read", "tool_input": {}, "cwd": str(PLUGIN)})
        for extra in ({"CLAUDE_PLUGIN_ROOT": str(PLUGIN)}, {"PLUGIN_ROOT": str(PLUGIN), "CLAUDE_PLUGIN_ROOT": str(PLUGIN)}):
            r = subprocess.run(["bash", "-c", cmd], input=payload, env=_env(**extra), capture_output=True, text=True, timeout=60)
            self.assertEqual(r.returncode, 0, r.stderr)
            if r.stdout.strip():
                json.loads(r.stdout)


class HarnessDetector(unittest.TestCase):
    CASES = [
        ({}, {}, "unknown"),
        ({}, {"CLAUDECODE": "1"}, "claude"),
        ({"turn_id": "t1"}, {}, "codex"),
        ({}, {"PLUGIN_ROOT": "/x"}, "codex"),
        ({}, {"CODEX_HOME": "/x"}, "codex"),
        ({}, {"OMP_X": "1"}, "omp"),
        ({"turn_id": "t"}, {"CLAUDECODE": "1"}, "codex"),
        ({}, {"ATLAS_HARNESS": "omp", "PLUGIN_ROOT": "/x"}, "omp"),
        ({}, {"ATLAS_HARNESS": "bogus", "CLAUDECODE": "1"}, "claude"),
        (None, {"CLAUDE_CODE_ENTRYPOINT": "cli"}, "claude"),
    ]

    def test_recognises_codex_and_matches_analytics(self):
        for payload, env, want in self.CASES:
            self.assertEqual(atlas_harness.detect_harness(payload, env), want, (payload, env))
            self.assertEqual(atlas_analytics.detect_harness(payload, env), want, (payload, env))

    def test_ask_becomes_deny_only_under_codex(self):
        reason = "atlas git policy: this would push to main."
        d, r = atlas_harness.codex_safe_decision("ask", reason, "codex")
        self.assertEqual(d, "deny")
        self.assertTrue(r.startswith(reason))
        self.assertIn("re-run after confirming with the user", r)
        for h in ("claude", "omp", "unknown"):
            self.assertEqual(atlas_harness.codex_safe_decision("ask", reason, h), ("ask", reason))
        self.assertEqual(atlas_harness.codex_safe_decision("deny", reason, "codex"), ("deny", reason))

    def test_output_adapter_drops_bare_allow_and_keeps_updated_input(self):
        bare = {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "allow"}}
        out = atlas_harness.codex_safe_output(bare, "codex")
        self.assertNotIn("permissionDecision", out["hookSpecificOutput"])
        keep = {"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "allow", "updatedInput": {"a": 1}}}
        self.assertEqual(atlas_harness.codex_safe_output(keep, "codex")["hookSpecificOutput"]["permissionDecision"], "allow")


class AskBehaviour(unittest.TestCase):
    def _run(self, script, payload, args=(), **env):
        r = subprocess.run(
            [sys.executable, "-S", str(HERE / script), *args], input=json.dumps(payload),
            env=_env(**env), capture_output=True, text=True, timeout=60,
        )
        self.assertEqual(r.returncode, 0, r.stderr)
        return json.loads(r.stdout)["hookSpecificOutput"] if r.stdout.strip() else {}

    def _cases(self):
        solo = make_repo(other_branch=False)
        return [
            ("push to protected branch", bash("git push origin main", solo)),
            (
                "pull request",
                {"hook_event_name": "PreToolUse", "tool_name": "mcp__github__create_pull_request", "tool_input": {}, "cwd": str(solo)},
            ),
            ("atlas_git allow", bash("python3 atlas_git.py allow main --reason x", solo)),
        ]

    def test_claude_payload_still_asks(self):
        for label, payload in self._cases():
            for script, args in (("git_guard.py", ()), ("event_dispatch.py", ("PreToolUse",))):
                spec = self._run(script, payload, args, CLAUDECODE="1")
                self.assertEqual(spec.get("permissionDecision"), "ask", (label, script))

    def test_codex_payload_never_asks(self):
        for label, payload in self._cases():
            codex = dict(payload, turn_id="turn-1")
            for script, args in (("git_guard.py", ()), ("event_dispatch.py", ("PreToolUse",))):
                spec = self._run(script, codex, args)
                self.assertEqual(spec.get("permissionDecision"), "deny", (label, script))
                self.assertIn("re-run after confirming with the user", spec["permissionDecisionReason"])

    def test_codex_env_alone_selects_codex(self):
        label, payload = self._cases()[0]
        spec = self._run("git_guard.py", payload, PLUGIN_ROOT=str(PLUGIN), CLAUDE_PLUGIN_ROOT=str(PLUGIN))
        self.assertEqual(spec["permissionDecision"], "deny")

    def test_atlas_git_check_exits_deny_under_codex_and_ask_under_claude(self):
        repo = make_repo(other_branch=False)
        script = str(PLUGIN / "scripts" / "atlas_git.py")
        for extra, code in (({"CLAUDECODE": "1"}, 3), ({"ATLAS_HARNESS": "codex"}, 4)):
            r = subprocess.run(
                [sys.executable, script, "--root", str(repo), "check", "push", "--branch", "main"],
                env=_env(**extra), capture_output=True, text=True, timeout=60,
            )
            self.assertEqual(r.returncode, code, r.stdout + r.stderr)
            if code == 4:
                self.assertIn("re-run after confirming with the user", json.loads(r.stdout)["reason"])

    def test_no_hook_source_emits_ask_outside_the_helper(self):
        """Only git_guard builds an ask, and it routes through atlas_harness before writing."""
        src = (HERE / "git_guard.py").read_text("utf-8")
        self.assertIn("atlas_harness.codex_safe_decision", src)
        for path in HERE.glob("*.py"):
            if path.name.startswith("test_") or path.name == "git_guard.py":
                continue
            self.assertNotRegex(path.read_text("utf-8"), r'"permissionDecision"\s*:\s*"ask"', path.name)


