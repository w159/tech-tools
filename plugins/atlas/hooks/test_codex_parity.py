class CodexHookMatchers(unittest.TestCase):
    def _matchers(self, event):
        return [g.get("matcher") for g in CODEX_HOOKS["hooks"][event]]

    def test_every_dispatch_tool_is_matched_by_a_codex_tool_name(self):
        """What Codex sends as tool_name (plus its matcher aliases) must reach each hook group."""
        def matches(pattern, names):  # codex HookMatcher: exact for [A-Za-z0-9_|], else unanchored regex
            if pattern in (None, "", "*"):
                return True
            if re.fullmatch(r"[A-Za-z0-9_|]+", pattern):
                return any(n in pattern.split("|") for n in names)
            return any(re.search(pattern, n) for n in names)

        seen = {"Bash": ["Bash"], "apply_patch": ["apply_patch", "Write", "Edit"], "spawn_agent": ["spawn_agent", "Agent"],
                "update_plan": ["update_plan"], "mcp__x__ctx_read": ["mcp__x__ctx_read"]}
        for tool, names in seen.items():
            self.assertTrue(any(matches(m, names) for m in self._matchers("PostToolUse")), tool)
        self.assertTrue(matches(self._matchers("PreToolUse")[0], ["spawn_agent", "Agent"]))
        self.assertTrue(matches("Edit|apply_patch|Write", seen["apply_patch"]))
        fmt = next(g["matcher"] for g in CODEX_HOOKS["hooks"]["PostToolUse"] if "format_after_edit" in json.dumps(g))
        self.assertTrue(matches(fmt, seen["apply_patch"]))
        self.assertFalse(matches(fmt, ["Bash"]))
        self.assertNotIn("MultiEdit", json.dumps(CODEX_HOOKS))
        self.assertNotIn("TaskCreate", json.dumps(CODEX_HOOKS))

    def test_regex_matchers_are_anchored(self):
        for event in ("PreToolUse", "PostToolUse"):
            for m in self._matchers(event):
                if m not in (None, "", "*") and not re.fullmatch(r"[A-Za-z0-9_|]+", m):
                    self.assertTrue(m.startswith("^(") and m.endswith(")$"), m)

    def test_session_end_fits_the_codex_three_second_clamp(self):
        for g in CODEX_HOOKS["hooks"]["SessionEnd"]:
            for h in g["hooks"]:
                self.assertLessEqual(h["timeout"], 3)
        self.assertGreater(HOOKS["hooks"]["SessionEnd"][0]["hooks"][0]["timeout"], 3, "Claude Code keeps its own budget")

    def test_matcher_translation_cases(self):
        f = gen_codex_hooks.codex_matcher
        self.assertEqual(f("Bash"), "Bash")
        self.assertEqual(f("*"), "*")
        self.assertIsNone(f("Read|Grep|Glob"))
        self.assertEqual(f("Edit|Write|MultiEdit|NotebookEdit"), "Edit|apply_patch|Write")
        self.assertEqual(f("Agent|Task"), "Agent|spawn_agent")
        self.assertEqual(f("TodoWrite|mcp__.*ctx_read|mcp__.*"), "^(update_plan|mcp__.*)$")


class CodexVerdictParity(unittest.TestCase):
    """The same hook verdicts for the Codex-shaped and the Claude-shaped payload."""

    def _dispatch(self, payload, event="PreToolUse", **env):
        r = subprocess.run([sys.executable, "-S", str(HERE / "event_dispatch.py"), event], input=json.dumps(payload),
                           env=_env(**env), capture_output=True, text=True, timeout=90)
        self.assertEqual(r.returncode, 0, r.stderr)
        return json.loads(r.stdout) if r.stdout.strip() else {}

    def test_force_push_to_main_same_verdict(self):
        repo = make_repo(other_branch=False)
        claude = bash("git push --force origin main", repo)
        codex = dict(claude, turn_id="t1")
        c = self._dispatch(claude, CLAUDECODE="1")["hookSpecificOutput"]
        x = self._dispatch(codex)["hookSpecificOutput"]
        self.assertEqual(c["permissionDecision"], "deny")
        self.assertEqual(x["permissionDecision"], "deny")
        self.assertTrue(x["permissionDecisionReason"].startswith(c["permissionDecisionReason"].rstrip()))

    def test_apply_patch_edit_matches_claude_edit(self):
        repo = make_repo(other_branch=False)
        target = Path(repo) / "pkg" / "a.py"
        target.parent.mkdir(exist_ok=True)
        target.write_text("old\n")
        claude = {"hook_event_name": "PreToolUse", "tool_name": "Edit", "cwd": str(repo),
                  "tool_input": {"file_path": str(target), "old_string": "old", "new_string": "new"}}
        codex = {"hook_event_name": "PreToolUse", "turn_id": "t1", "tool_name": "apply_patch", "cwd": str(repo),
                 "tool_input": {"command": PATCH_UPDATE}}
        self.assertEqual(self._dispatch(codex), self._dispatch(claude, CLAUDECODE="1"))
        post = dict(claude, hook_event_name="PostToolUse", tool_response={})
        post_x = dict(codex, hook_event_name="PostToolUse", tool_response={})
        self.assertEqual(self._dispatch(post_x, "PostToolUse"), self._dispatch(post, "PostToolUse", CLAUDECODE="1"))

    def test_apply_patch_add_file_over_existing_matches_claude_write_deny(self):
        """dispatch_tripwire denies a Write of device arguments over an existing file; an apply_patch
        Add File with the same body gets the same verdict."""
        repo = make_repo(other_branch=False)
        target = Path(repo) / "args.json"
        target.write_text("{}\n")
        claude = {"hook_event_name": "PreToolUse", "tool_name": "Write", "cwd": str(repo),
                  "tool_input": {"file_path": str(target), "content": '{"pattern": "x"}'}}
        codex = {"hook_event_name": "PreToolUse", "turn_id": "t1", "tool_name": "apply_patch", "cwd": str(repo),
                 "tool_input": {"command": '*** Begin Patch\n*** Add File: args.json\n+{"pattern": "x"}\n*** End Patch'}}
        want = self._dispatch(claude, CLAUDECODE="1")
        self.assertEqual(want["hookSpecificOutput"]["permissionDecision"], "deny")
        self.assertEqual(self._dispatch(codex), want)

    def test_translated_edit_is_gated_by_the_edit_binding(self):
        """The Edit-only hook (edit_read_nudge) is selected for an apply_patch payload."""
        import event_dispatch

        self.assertIn("edit_read_nudge", event_dispatch.select("PreToolUse", "Edit"))
        out = atlas_harness.normalize_tool_payload(codex_tool("apply_patch", {"command": PATCH_UPDATE}))
        self.assertIn("edit_read_nudge", event_dispatch.select("PreToolUse", out["tool_name"]))
        self.assertIn("dispatch_tripwire", event_dispatch.select("PreToolUse", "Agent"))

    def test_updated_input_is_dropped_for_translated_tools(self):
        import event_dispatch

        merged = (0, json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "updatedInput": {"file_path": "x"}}}) + "\n", "")
        out = json.loads(event_dispatch._strip_updated_input(merged)[1])
        self.assertNotIn("updatedInput", out["hookSpecificOutput"])


class SessionEndDetach(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp()
        self.transcript = os.path.join(self.tmp, "sess-detach.jsonl")
        line = json.dumps({"sessionId": "sess-detach", "cwd": "/repo/demo", "type": "user", "uuid": "u1",
                           "timestamp": "2026-07-12T12:00:00Z", "message": {"role": "user", "content": [{"type": "text", "text": "hi"}]}})
        Path(self.transcript).write_text(line + "\n")
        self.db = os.path.join(self.tmp, "atlas.db")
        self.env = _env(ATLAS_DB=self.db, ATLAS_HOOKSTATE_DIR=os.path.join(self.tmp, "hs"), ATLAS_INGEST="on", ATLAS_CHRONICLE="off")

    def _rows(self):
        import sqlite3

        if not os.path.exists(self.db):
            return 0
        c = sqlite3.connect(self.db)
        try:
            return c.execute("SELECT COUNT(*) FROM session_logs").fetchone()[0]
        except sqlite3.Error:
            return 0
        finally:
            c.close()

    def _run(self, event, **extra):
        payload = json.dumps({"hook_event_name": event, "session_id": "sess-detach", "transcript_path": self.transcript, "cwd": self.tmp})
        t0 = time.monotonic()
