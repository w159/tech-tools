class ManifestParity(unittest.TestCase):
    def test_identity_matches_claude_manifest(self):
        for key in ("name", "version", "description", "keywords", "license"):
            self.assertEqual(CODEX[key], CLAUDE[key], key)

    def test_marketplaces_agree_on_version_and_source(self):
        claude_mk = json.loads((REPO / ".claude-plugin" / "marketplace.json").read_text("utf-8"))
        codex_mk = json.loads((REPO / ".agents" / "plugins" / "marketplace.json").read_text("utf-8"))
        self.assertEqual(codex_mk["name"], claude_mk["name"])
        want = next(p for p in claude_mk["plugins"] if p["name"] == "atlas")
        got = next(p for p in codex_mk["plugins"] if p["name"] == "atlas")
        self.assertEqual(got["source"], want["source"])
        self.assertEqual(want["version"], CODEX["version"])
