"""Render a ScanResult as text, JSON, SARIF 2.1.0, or Markdown; render the rule catalog."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from . import __version__
from .catalog import RULES, RULES_BY_ID
from .engine import ScanResult

SARIF_SCHEMA = "https://json.schemastore.org/sarif-2.1.0.json"
SARIF_LEVEL = {"error": "error", "warning": "warning", "note": "note"}


def to_text(r: ScanResult) -> str:
    lines = [f"{f.path}:{f.line}: {f.rule} [{f.severity}] {f.message}" for f in r.findings]
    for e in r.errors:
        lines.append(f"{e['path']}: PARSE {e['error']}")
    counts = Counter(f.severity for f in r.findings)
    lines.append(
        f"{len(r.findings)} findings ({counts['error']} error, {counts['warning']} warning, {counts['note']} note) "
        f"in {r.files_scanned} files; {r.suppressed} suppressed, {r.baselined} baselined, {len(r.errors)} parse errors"
    )
    return "\n".join(lines)


def to_json(r: ScanResult) -> str:
    return json.dumps({
        "tool": "principles", "version": __version__, "root": r.root, "rules": r.rules,
        "files_scanned": r.files_scanned, "suppressed": r.suppressed, "baselined": r.baselined,
        "summary": dict(Counter(f.rule for f in r.findings)),
        "findings": [f.to_dict() for f in r.findings], "errors": r.errors,
    }, indent=2)


def to_sarif(r: ScanResult) -> str:
    rule_ids = sorted({f.rule for f in r.findings} | set(r.rules))
    rules = []
    for rid in rule_ids:
        rule = RULES_BY_ID[rid]
        rules.append({
            "id": rid,
            "name": rule.title.replace(" ", ""),
            "shortDescription": {"text": rule.title},
            "fullDescription": {"text": f"{rule.principle}. Detects: {rule.detects}"},
            "defaultConfiguration": {"level": SARIF_LEVEL[rule.severity]},
            "properties": {"sources": list(rule.sources)},
        })
    index = {rid: i for i, rid in enumerate(rule_ids)}
    results = []
    for f in r.findings:
        results.append({
            "ruleId": f.rule,
            "ruleIndex": index[f.rule],
            "level": SARIF_LEVEL[f.severity],
            "message": {"text": f"{f.message} ({f.principle}; {f.source})"},
            "locations": [{"physicalLocation": {"artifactLocation": {"uri": f.path, "uriBaseId": "SRCROOT"},
                                                "region": {"startLine": f.line, "endLine": max(f.end_line, f.line)}}}],
            "partialFingerprints": {"principles/v1": f.fingerprint()},
        })
    log = {
        "$schema": SARIF_SCHEMA,
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {"name": "principles", "version": __version__,
                                "informationUri": "https://github.com/w159/tech-tools/tree/main/plugins/programmer",
                                "rules": rules}},
            "originalUriBaseIds": {"SRCROOT": {"uri": Path(r.root).as_uri().rstrip("/") + "/"}},
            "results": results,
        }],
    }
    return json.dumps(log, indent=2)


def to_markdown(r: ScanResult) -> str:
    counts = Counter(f.rule for f in r.findings)
    out = ["# Principles scan", "", f"Root: `{r.root}`  ", f"Files: {r.files_scanned}, findings: {len(r.findings)}, "
           f"suppressed: {r.suppressed}, baselined: {r.baselined}", "", "| Rule | Title | Count |", "|---|---|---|"]
    for rid in r.rules:
        if counts[rid]:
            out.append(f"| {rid} | {RULES_BY_ID[rid].title} | {counts[rid]} |")
    out += ["", "## Findings", ""]
    for f in r.findings:
        out.append(f"- `{f.path}:{f.line}` **{f.rule}** ({f.severity}) {f.message} Source: {f.source}.")
    return "\n".join(out) + "\n"


def catalog_markdown() -> str:
    out = [
        "# Principle catalog",
        "",
        "Generated by `python3 scripts/principles catalog`. Do not edit by hand; edit `scripts/principles/catalog.py`.",
        "",
        f"{len(RULES)} detected rules. Severity is the default; thresholds are set per rule in `.principles.toml`.",
        "",
        "| ID | Rule | Principle | Severity | Detects | Sources | Options |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in RULES:
        opts = ", ".join(f"{k}={v}" for k, v in r.options.items() if not isinstance(v, list)) or "-"
        out.append(f"| {r.id} | {r.title} | {r.principle} | {r.severity} | {r.detects} | {'; '.join(r.sources)} | {opts} |")
    return "\n".join(out) + "\n"
